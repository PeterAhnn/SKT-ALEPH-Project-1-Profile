import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fixture, kind } from './browser-fixture.mjs';

const f = await fixture();
try {
  const accountA = (await f.register()).user;
  await f.logout();
  const aOptions = (await f.post('/api/passkeys/login/options', { name: 'virtual-a' })).body;
  const aProof = await f.page.evaluate(async optionsJSON => window.SimpleWebAuthnBrowser.startAuthentication({ optionsJSON }), aOptions.publicKey);
  assert.equal((await f.post('/api/passkeys/login/verify', { challengeId: aOptions.challengeId, response: aProof })).status, 200);
  const contextB = await f.browser.newContext({ viewport: { width: 1280, height: 900 } });
  const pageB = await contextB.newPage();
  const cdpB = await contextB.newCDPSession(pageB);
  await cdpB.send('WebAuthn.enable');
  await cdpB.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
  await pageB.goto(f.base);
  await pageB.locator('#account-name').fill('virtual-b');
  await pageB.locator('#credential-name').fill('다른 계정의 가상 인증기');
  const registered = pageB.waitForResponse(response => response.url().endsWith('/register/verify'));
  await pageB.locator('#register-passkey').click();
  const bRegistered = await registered;
  assert.equal(bRegistered.status(), 200);
  const accountB = (await bRegistered.json()).user;
  await pageB.locator('#private-content article').nth(2).waitFor();
  const bPost = async (path, data) => { const response = await contextB.request.post(f.base + path, { headers: { origin: f.base }, data }); return { status: response.status(), body: await response.json() }; };
  assert.equal((await bPost('/api/logout', {})).status, 200);
  const bOptions = (await bPost('/api/passkeys/login/options', { name: 'virtual-b' })).body;
  const bProof = await pageB.evaluate(async optionsJSON => window.SimpleWebAuthnBrowser.startAuthentication({ optionsJSON }), bOptions.publicKey);
  assert.equal((await bPost('/api/passkeys/login/verify', { challengeId: bOptions.challengeId, response: bProof })).status, 200);
  const counts = () => f.store.transact(state => ({ a: state.users[accountA.id].items.length, b: state.users[accountB.id].items.length }));
  const before = await counts();
  const records = [];
  const get = async (context, path, label) => {
    const response = await context.request.get(f.base + path);
    const body = await response.json();
    records.push({ label, request: { method: 'GET', path, cookie: '[가림]' }, response: { status: response.status(), body } });
    return { status: response.status(), body };
  };
  const ownA = await get(f.context, '/api/private/items', 'A의 정상 조회');
  const ownB = await get(contextB, '/api/private/items', 'B의 정상 조회');
  assert.equal(ownA.status, 200); assert.equal(ownB.status, 200);
  assert.notDeepEqual(ownA.body.items, ownB.body.items);
  assert.equal((await get(f.context, `/api/private/accounts/${accountB.id}/items`, 'A에서 B로 접근')).status, 403);
  assert.equal((await get(contextB, `/api/private/accounts/${accountA.id}/items`, 'B에서 A로 접근')).status, 403);
  const tamperedA = await get(f.context, `/api/private/items?userId=${accountB.id}&owner=${accountB.id}`, 'A가 주소에 B를 지정');
  const tamperedB = await get(contextB, `/api/private/items?userId=${accountA.id}&owner=${accountA.id}`, 'B가 주소에 A를 지정');
  assert.equal(tamperedA.body.owner, accountA.id); assert.equal(tamperedB.body.owner, accountB.id);
  const after = await counts();
  assert.deepEqual(after, before);
  await mkdir('verification/card5', { recursive: true });
  await f.page.reload();
  await f.page.locator('#private-content article').nth(2).waitFor();
  await f.page.locator('#private-space').screenshot({ path: 'verification/card5/account-a.png' });
  await pageB.reload();
  await pageB.locator('#private-content article').nth(2).waitFor();
  await pageB.locator('#private-space').screenshot({ path: 'verification/card5/account-b.png' });
  await f.page.getByText('과제 확인 기록 보관', { exact: true }).click();
  const download = f.page.waitForEvent('download');
  await f.page.getByRole('button', { name: '이 탭의 확인 기록 내려받기', exact: true }).click();
  await (await download).saveAs('verification/card5/browser-export.json');
  const exported = await readFile('verification/card5/browser-export.json', 'utf8');
  for (const cookie of await f.context.cookies()) assert.ok(!exported.includes(cookie.value), '확인 기록에 쿠키 값이 포함되었습니다.');
  assert.ok(!exported.includes('privateKey'));
  await writeFile('verification/card5/isolation-evidence.json', JSON.stringify({ checkedAt: new Date().toISOString(), kind, accounts: [accountA, accountB], records, countsBefore: before, countsAfter: after, source: 'server/app.mjs의 currentUser 및 /api/private/* 처리', browserExportContainsCookieValues: false, browserExportContainsPrivateKey: false }, null, 2));
  console.log('카드 5: 계정 2개·양방향403·주소 변조에도 본인 자료·건수 보존·증거 내보내기 확인 완료');
} finally { await f.close(); }
